#!/usr/bin/env node
// Generates TypeScript types from the migrated LOCAL Supabase schema into
// packages/shared/src/database.types.ts (master §11.6, §13.13).
//
//   pnpm db:types          regenerate the file
//   pnpm db:types --check  fail if the committed file is out of date (CI)
//
// Requires the local stack: `pnpm exec supabase start` (+ `db reset`).
import { execSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { format, resolveConfig } from 'prettier';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const target = resolve(root, 'packages/shared/src/database.types.ts');
const check = process.argv.includes('--check');

// Fixed command string (no user input), run through the platform shell so
// pnpm's .cmd shim resolves on Windows.
const generated = execSync('pnpm exec supabase gen types typescript --local --schema public', {
  cwd: root,
  encoding: 'utf8',
  stdio: ['ignore', 'pipe', 'inherit'],
});

const header =
  '// AUTO-GENERATED by scripts/gen-db-types.mjs from the migrated Supabase schema.\n' +
  '// Do not edit by hand — change a migration and run `pnpm db:types`.\n\n';
const prettierConfig = (await resolveConfig(target)) ?? {};
const output = await format(header + generated, { ...prettierConfig, filepath: target });

if (check) {
  let current = '';
  try {
    current = readFileSync(target, 'utf8');
  } catch {
    // missing file is treated as out of date
  }
  if (current !== output) {
    console.error(
      'packages/shared/src/database.types.ts is out of date. Run `pnpm db:types` and commit.',
    );
    process.exit(1);
  }
  console.warn('database.types.ts is up to date.');
} else {
  writeFileSync(target, output);
  console.warn(`Wrote ${target}`);
}
